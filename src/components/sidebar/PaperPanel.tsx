const DEPTH_LABELS = {
  chapters: ["Chapters", "Chapters and sections", "Down to subsections"],
  sections: ["Sections", "Sections and subsections", "Down to subsubsections"],
};

/** The last "Contents & lists…" request scrolled to; the panel remounts on every tab switch. */
let revealed = 0;

/** Word's "Table of contents" settings: LaTeX regenerates the lists on every typeset. */
function ContentsSettings() {
  const meta = useStore((s) => s.meta)!;
  const reveal = useStore((s) => s.contentsReveal);
  const ref = useRef<HTMLElement>(null);
  const [flash, setFlash] = useState(false);

  useEffect(() => {
    if (reveal <= revealed || !ref.current) return;
    revealed = reveal;
    ref.current.scrollIntoView({ behavior: "smooth", block: "start" });
    setFlash(true);
    const t = setTimeout(() => setFlash(false), 1200);
    return () => clearTimeout(t);
  }, [reveal]);

  const labels = DEPTH_LABELS[usesChapters(meta.template) ? "chapters" : "sections"];
  return (
    <section
      ref={ref}
      aria-labelledby="pf-contents-heading"
      className={cx("scroll-mt-3 space-y-1.5 rounded-lg transition-shadow", flash && "ring-2 ring-accent/50 ring-offset-4 ring-offset-panel")}
    >
      <h3 id="pf-contents-heading" className="text-[11px] font-semibold uppercase tracking-wide text-muted">
        Contents
      </h3>
      <div className="space-y-0.5">
        <Checkbox checked={meta.toc ?? false} onChange={(toc) => updateMeta({ toc })} label="Table of contents" />
        <Checkbox checked={meta.lof ?? false} onChange={(lof) => updateMeta({ lof })} label="List of figures" />
        <Checkbox checked={meta.lot ?? false} onChange={(lot) => updateMeta({ lot })} label="List of tables" />
      </div>
      <label className="flex items-center justify-between gap-3 pt-1">
        <span className={cx("text-[12px]", meta.toc ? "text-muted" : "text-faint")}>Depth</span>
        <Select
          className="w-52"
          disabled={!meta.toc}
          value={meta.tocDepth ?? 2}
          onChange={(e) => updateMeta({ tocDepth: Number(e.target.value) })}
        >
          {labels.map((label, i) => (
            <option key={i} value={i + 1}>
              {i + 1} — {label}
            </option>
          ))}
        </Select>
      </label>
      <p className="text-[11px] leading-snug text-faint">
        Generated by LaTeX on every typeset, like Word's "Update table". Type /toc in the text to place one at a
        specific spot.
      </p>
    </section>
  );
}

export function PaperPanel() {
  const meta = useStore((s) => s.meta);
  const dir = useStore((s) => s.dir);
  const [keywords, setKeywords] = useState("");

  // Seeded once per project: re-joining on every keystroke would move the caret.
  useEffect(() => setKeywords(meta?.keywords.join(", ") ?? ""), [dir]);

  if (!meta) return null;

  function setAuthor(index: number, patch: Partial<Author>) {
    updateMeta({ authors: meta!.authors.map((a, i) => (i === index ? { ...a, ...patch } : a)) });
  }

  return (
    <div className="space-y-5 p-4">
      <Field label="Title">
        <Textarea value={meta.title} maxRows={4} onChange={(e) => updateMeta({ title: e.target.value })} placeholder="Paper title" />
      </Field>

      <Field label="Authors" hint="Order is kept">
        <div className="space-y-2">
          {meta.authors.map((author, i) => (
            <div key={i} className="group relative space-y-1.5 rounded-lg border border-line bg-raised/50 p-2">
              <Input value={author.name} placeholder="Full name" onChange={(e) => setAuthor(i, { name: e.target.value })} />
              <Input
                value={author.affiliation}
                placeholder="Affiliation"
                onChange={(e) => setAuthor(i, { affiliation: e.target.value })}
              />
              <Input
                value={author.email}
                type="email"
                placeholder="Email"
                onChange={(e) => setAuthor(i, { email: e.target.value })}
              />
              {meta.authors.length > 1 && (
                <button
                  aria-label={`Remove ${author.name || "author"}`}
                  onClick={() => updateMeta({ authors: meta.authors.filter((_, j) => j !== i) })}
                  className="absolute -right-2 -top-2 hidden h-5 w-5 items-center justify-center rounded-full border border-line bg-panel text-muted shadow group-hover:flex hover:text-danger"
                >
                  <X size={12} />
                </button>
              )}
            </div>
          ))}
          <Button
            size="sm"
            variant="ghost"
            className="w-full"
            onClick={() => updateMeta({ authors: [...meta.authors, { name: "", affiliation: "", email: "" }] })}
          >
            <Plus size={14} /> Add author
          </Button>
        </div>
      </Field>

      <Field label="Abstract" hint="Markdown and $math$">
        <Textarea
          value={meta.abstract}
          maxRows={12}
          onChange={(e) => updateMeta({ abstract: e.target.value })}
          placeholder="A short summary of the paper"
        />
      </Field>

      <Field label="Keywords" hint="Comma separated">
        <Input
          value={keywords}
          placeholder="typesetting, LaTeX"
          onChange={(e) => {
            setKeywords(e.target.value);
            updateMeta({ keywords: e.target.value.split(",").map((k) => k.trim()).filter(Boolean) });
          }}
        />
      </Field>

      <ContentsSettings />

      <PageSetupPanel />

      <div className="grid grid-cols-2 gap-3">
        <Field label="Language">
          <Select className="w-full" value={meta.language} onChange={(e) => updateMeta({ language: e.target.value })}>
            {LANGUAGES.map((l) => (
              <option key={l.id} value={l.id}>
                {l.label}
              </option>
            ))}
          </Select>
        </Field>
        <Field label="Date">
          <Input value={meta.date} placeholder="Hidden" onChange={(e) => updateMeta({ date: e.target.value })} />
        </Field>
      </div>

      <Field label="BibTeX style" hint="Advanced">
        <Input
          value={meta.bibStyle}
          className="font-mono text-xs"
          placeholder={templateInfo(meta.template).defaultBibStyle}
          onChange={(e) => updateMeta({ bibStyle: e.target.value })}
        />
      </Field>

      <LatexSettings />
      <StylesPanel />
    </div>
  );
}

function parseOptions(text: string): string[] {
  return text.split(",").map((o) => o.trim()).filter(Boolean);
}

function run(task: () => Promise<unknown>) {
  task().catch((e) => notify(String(e), "error"));
}

/** Class options, the project preamble and the template file: LaTeX for those who want it. */
function LatexSettings() {
  const meta = useStore((s) => s.meta)!;
  const dir = useStore((s) => s.dir);
  const hasPreamble = useStore((s) => s.preamble !== null);
  const [classOptions, setClassOptions] = useState("");
  const [confirmEject, setConfirmEject] = useState(false);

  // Seeded per project and when page setup changes the options, but never rewritten while typing.
  const current = (meta.classOptions ?? []).join(", ");
  useEffect(() => setClassOptions((text) => (parseOptions(text).join(", ") === current ? text : current)), [dir, current]);

  const templateFile = meta.templateFile ?? "";
  const label = templateInfo(meta.template).label;
  return (
    <section aria-labelledby="pf-latex-heading" className="space-y-3">
      <h3 id="pf-latex-heading" className="text-[11px] font-semibold uppercase tracking-wide text-muted">
        LaTeX
      </h3>
      <Field label="Class options" hint="Comma separated">
        <Input
          value={classOptions}
          className="font-mono text-xs"
          placeholder="twocolumn, 10pt"
          onChange={(e) => {
            setClassOptions(e.target.value);
            updateMeta({ classOptions: parseOptions(e.target.value) });
          }}
        />
      </Field>
      <p className="-mt-1.5 text-[11px] leading-snug text-faint">
        An option replaces the template's own of the same kind: 10pt replaces 11pt, letterpaper replaces a4paper.
      </p>

      <div className="flex items-center justify-between gap-3">
        <span className="text-[12px] text-muted">Preamble</span>
        <Button size="sm" onClick={openPreamble}>
          <FileCog size={13} /> {hasPreamble ? "Edit preamble.tex" : "Create preamble.tex"}
        </Button>
      </div>

      <div className="space-y-1.5">
        <div className="flex items-center justify-between gap-3">
          <span className="text-[12px] text-muted">Template</span>
          {templateFile ? (
            <Button size="sm" onClick={() => run(restoreTemplate)}>
              <Undo2 size={13} /> Restore built-in template
            </Button>
          ) : (
            <Button size="sm" disabled={confirmEject} onClick={() => setConfirmEject(true)}>
              <PackageOpen size={13} /> Eject template…
            </Button>
          )}
        </div>
        {templateFile ? (
          <p className="text-[11px] leading-snug text-faint">
            Typesetting with <code className="font-mono">{templateFile}</code>, your copy of {label}. Restoring keeps the copy
            on disk.
          </p>
        ) : (
          confirmEject && (
            <div
              ref={(el) => el?.scrollIntoView({ behavior: "smooth", block: "nearest" })}
              role="alertdialog"
              aria-label="Eject template"
              className="space-y-2 rounded-lg border border-line bg-raised/50 p-2.5">
              <p className="text-[12px] leading-snug text-muted">
                Copy the {label} template into this project's <code className="font-mono">template/</code> folder and
                typeset with that copy, so you can edit it. Later improvements to the built-in template will not reach it.
              </p>
              <div className="flex justify-end gap-1.5">
                <Button size="sm" variant="ghost" onClick={() => setConfirmEject(false)}>
                  Cancel
                </Button>
                <Button
                  size="sm"
                  variant="primary"
                  onClick={() => {
                    setConfirmEject(false);
                    run(ejectTemplate);
                  }}
                >
                  Eject
                </Button>
              </div>
            </div>
          )
        )}
      </div>
    </section>
  );
}
